# Writes fpu_soft_tables.h, the constants fpu_soft.c works with: 2/pi to
# 16,896 bits for the reduction of FSIN, FCOS and FTAN's operands, pi, ln 2,
# ln 10 and log2(10) in binary64 parts, and FMOVECR's ROM constants rounded
# once to the extended format. All in Python's integers, exactly.
#   python3 -I src/cpu/fpu_soft_gen.py > src/cpu/fpu_soft_tables.h
import sys

P = 17400                       # working bits

def atan_inv(n, bits):          # atan(1/n) * 2^bits
    one = 1 << bits
    s, t, k, sign, n2 = 0, one // n, 1, 1, n * n
    while t:
        s += sign * (t // k)
        t //= n2; k += 2; sign = -sign
    return s

def pi_fixed(bits):             # Machin: pi = 16 atan(1/5) - 4 atan(1/239)
    g = bits + 32
    return (16 * atan_inv(5, g) - 4 * atan_inv(239, g)) >> 32

def ln_fixed(num, den, bits):   # ln(num/den) = 2 atanh((num-den)/(num+den)), num > den
    g = bits + 32
    a, b = num - den, num + den
    t = (a << g) // b
    s, k, a2, b2 = 0, 1, a * a, b * b
    while t:
        s += t // k
        t = t * a2 // b2; k += 2
    return (2 * s) >> 32

def round_to(num, den, nbits):
    """num/den > 0 rounded to nbits significant bits, nearest/even: (m, e) with value m * 2^e"""
    e = num.bit_length() - den.bit_length() - nbits
    while True:
        q, r = divmod(num << -e if e < 0 else num, den if e < 0 else den << e)
        if q >> nbits: e += 1; continue
        if not q >> (nbits - 1): e -= 1; continue
        break
    twice = 2 * r
    d = den if e < 0 else den << e
    if twice > d or (twice == d and q & 1):
        q += 1
        if q >> nbits: q >>= 1; e += 1
    return q, e

def dbl(m, e):                  # a C hex double for m * 2^e
    if m == 0: return "0.0"
    s = "-" if m < 0 else ""
    m = abs(m)
    sh = m.bit_length() - 1
    return "%s0x%xp%+d" % (s, m, e) if sh < 0 else "%s0x1.%013xp%+d" % (s, (m << (52 - sh)) & ((1 << 52) - 1), e + sh)

def parts(num, den, widths):
    """num/den as a sum of doubles of the given significand widths, each rounded to nearest"""
    out = []
    for w in widths:
        if num == 0: out.append((0, 0)); continue
        neg = (num < 0) != (den < 0)
        m, e = round_to(abs(num), abs(den), w)
        if neg: m = -m
        out.append((m, e))
        # num/den -= m * 2^e
        if e >= 0: num = num - m * den * (1 << e)
        else: num, den = num * (1 << -e) - m * den, den * (1 << -e)
    return out

PIF = pi_fixed(P)               # pi * 2^P
ONE = 1 << P
LN2 = ln_fixed(2, 1, 400)
LN10 = ln_fixed(5, 4, 400) + 3 * LN2   # ln 10 = ln(5/4) + 3 ln 2
F = 1 << 400

o = sys.stdout
o.write("/* Generated by fpu_soft_gen.py: do not edit. Constants for fpu_soft.c. */\n")
def put(name, num, den, widths):
    for i, (m, e) in enumerate(parts(num, den, widths)):
        o.write("#define %s_%d %s\n" % (name, i + 1, dbl(m, e)))
put("FS_PIO2", PIF, 2 * ONE, [53, 53, 53])
put("FS_PI", PIF, ONE, [53, 53, 53])
put("FS_LN2", LN2, F, [36, 36, 53, 53])
put("FS_LN10", LN10, F, [53, 53, 53])
put("FS_LOG2_10", LN10, LN2, [53, 53, 53])
put("FS_INVLN2", F, LN2, [53, 53, 53])
put("FS_INVLN10", F, LN10, [53, 53, 53])

# series coefficients as double-doubles: 1/k! and 1/(2k+1)
def ddpair(num, den):
    (m1, e1), (m2, e2) = parts(num, den, [53, 53])
    return "{ %s, %s }" % (dbl(m1, e1), dbl(m2, e2))
import math
o.write("static const fs_dd fs_inv_fact[34] = {\n")
for k in range(34):
    o.write("    %s,\n" % ddpair(1, math.factorial(k)))
o.write("};\n")
o.write("static const fs_dd fs_inv_odd[40] = {   /* 1/(2k+1) */\n")
for k in range(40):
    o.write("    %s,\n" % ddpair(1, 2 * k + 1))
o.write("};\n")

# 2/pi's bits after the binary point, most significant first, 64 to a word
NB = 16384 + 512
two_over_pi = (ONE << (NB + 1)) // PIF       # floor(2/pi * 2^NB)
words = []
for i in range(NB // 64):
    words.append((two_over_pi >> (NB - 64 * (i + 1))) & ((1 << 64) - 1))
o.write("#define FS_TWO_OVER_PI_WORDS %d\n" % len(words))
o.write("static const uint64_t fs_two_over_pi[FS_TWO_OVER_PI_WORDS] = {\n")
for i in range(0, len(words), 4):
    o.write("    " + ", ".join("0x%016xull" % w for w in words[i:i + 4]) + ",\n")
o.write("};\n")

# FMOVECR: the 68881's ROM constants, each rounded to nearest at 64 bits,
# as GCC rounds the long double literals ac090_fpu.c gives the x87.
def ext(num, den):
    if num == 0: return (0, 0)
    m, e = round_to(num, den, 64)
    return (m, 0x3fff + e + 63)
E = 0; t = ONE; k = 0
while t: E += t; k += 1; t //= k
cr = {
    0x00: (PIF, ONE),
    0x0b: (LN2, LN10),                      # log10(2)
    0x0c: (E, ONE),                         # e
    0x0d: (F, LN2),                         # log2(e)
    0x0e: (F, LN10),                        # log10(e)
    0x0f: (0, 1),
    0x30: (LN2, F),
    0x31: (LN10, F),
    0x32: (1, 1), 0x33: (10, 1), 0x34: (100, 1), 0x35: (10**4, 1), 0x36: (10**8, 1),
    0x37: (10**16, 1), 0x38: (10**32, 1), 0x39: (10**64, 1), 0x3a: (10**128, 1),
    0x3b: (10**256, 1), 0x3c: (10**512, 1), 0x3d: (10**1024, 1), 0x3e: (10**2048, 1), 0x3f: (10**4096, 1),
}
o.write("static const struct { uint8_t off; uint16_t se; uint64_t m; } fs_fmovecr[] = {\n")
for off in sorted(cr):
    m, se = ext(*cr[off])
    o.write("    { 0x%02x, 0x%04x, 0x%016xull },\n" % (off, se, m))
o.write("};\n")
